def unicode_normalize(text: str) -> str:
    """Normalizes Unicode text to NFKD standard format."""
    if not text:
        return ""
    return unicodedata.normalize('NFKD', text).encode('ascii', 'ignore').decode('utf-8', 'ignore')

def expand_contractions(text: str) -> str:
    """Expands contractions in text using lookup map."""
    if not text:
        return ""
    tokens = text.split()
    expanded = [CONTRACTION_MAP.get(token.lower(), token) for token in tokens]
    return " ".join(expanded)
